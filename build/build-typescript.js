#!/usr/bin/env node

const { execSync } = require('child_process');
const { readdirSync, statSync, readFileSync, writeFileSync } = require('fs');
const { join } = require('path');

function findTsFiles(dir) {
  const results = [];
  try {
    const files = readdirSync(dir);
    for (const file of files) {
      const filePath = join(dir, file);
      const stat = statSync(filePath);
      if (stat.isDirectory()) {
        results.push(...findTsFiles(filePath));
      } else if (file.endsWith('.ts')) {
        results.push(filePath);
      }
    }
  } catch (err) {
    // Directory doesn't exist or can't be read
  }
  return results;
}

const tsFiles = findTsFiles('lib');

if (tsFiles.length === 0) {
  console.log('No TypeScript files found in lib/. Skipping TypeScript compilation.');
  process.exit(0);
}

try {
  execSync('tsc', { stdio: 'inherit' });
  
  // Add header comment to compiled files
  const compiledFiles = tsFiles.map(f => f.replace(/\.ts$/, '.js'));
  for (const jsFile of compiledFiles) {
    try {
      const content = readFileSync(jsFile, 'utf8');
      const sourceFile = jsFile.replace(/\.js$/, '.ts');
      const header = `/**
 * This file is automatically generated from ${sourceFile} by the TypeScript compiler.
 * DO NOT EDIT THIS FILE DIRECTLY - Edit ${sourceFile} instead and run \`npm run build:ts\`
 * to regenerate this file.
 */
`;
      if (!content.startsWith('/**')) {
        writeFileSync(jsFile, header + content, 'utf8');
      }
    } catch (err) {
      // File might not exist or be readable, skip
    }
  }
} catch (error) {
  process.exit(error.status || 1);
}
